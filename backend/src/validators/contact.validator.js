import { z } from 'zod';

export const createContactSchema = z.object({
  name: z.string().min(1, 'Contact name is required'),
  companyName: z.string().min(1, 'Company name is required').optional().nullable(),
  contactPerson: z.string().optional().nullable(),
  phone: z.string().min(10, 'Valid 10-digit phone number is required'),
  email: z.string().email('Invalid email address').optional().or(z.literal('')),
  assignedTo: z.string().optional().nullable(),
  estimatedValue: z.string().optional().nullable(),
  expectedCloseDate: z.string().optional().nullable(),
  description: z.string().optional().nullable(),
  notes: z.string().optional().nullable(),
  employeeCount: z.string().optional().nullable(),
  nextFollowDate: z.string().optional().nullable(),
  remarks: z.string().optional().nullable(),
  customProduct: z.string().optional().nullable(),
  internalReference: z.string().optional().nullable(),
  productCode: z.string().optional().nullable(),
  businessNeed: z.string().optional().nullable(),
  budgetRange: z.string().optional().nullable(),
  decisionMaker: z.string().optional().nullable(),
  purchaseTimeline: z.string().optional().nullable(),
  interestedService: z.string().optional().nullable(),
  priority: z.string().optional().nullable(),
  qualificationStatus: z.string().optional().nullable(),
  qualifiedBy: z.string().optional().nullable(),
  qualificationDate: z.string().optional().nullable(),
  unqualifiedReason: z.string().optional().nullable(),
  disqualificationReason: z.string().optional().nullable(),
  address: z.string().optional().nullable(),
  gstNumber: z.string().optional().nullable(),
  companyPan: z.string().optional().nullable(),
  panNumber: z.string().optional().nullable(),
  source: z.string().optional(),
  contactType: z.string().optional(),
  designation: z.string().optional(),
  category: z.string().optional(),
  productList: z.array(z.string()).optional(),
  serviceList: z.array(z.string()).optional(),
  status: z.string().optional(),
  stage: z.string().optional(),
});

export const updateContactSchema = createContactSchema.partial();
